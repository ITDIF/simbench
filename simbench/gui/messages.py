def explain(text: str) -> str:
    """给一句引擎/后端报错找中文说明；找不到回空串（调用方按口径原样显示）。"""
    if not text:
        return ""
    for fragment, hint in EXPLANATIONS:
        if fragment in text:
            return hint
    return ""


def with_explanation(text: str) -> str:
    """原文 + （有中文说明时）缩进一行的中文。**原文一个字都不动**（取证要用）。"""
    hint = explain(text)
    return f"{text}\n         ↳ {hint}" if hint else text
